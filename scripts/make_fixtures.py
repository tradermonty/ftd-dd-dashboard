#!/usr/bin/env python3
"""Build tests/fixtures/bars.json from the cached raw FMP chunks (data/raw/, no new calls).

Segments: "ftd_rich" (2018-09-04..2020-12-31, contains the Dec-2018 and Mar-2020 FTDs)
and "latest" (the last 300 bars of the cache).
"""

from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from engine import fetch  # noqa: E402

SEGMENTS = {"ftd_rich": ("2018-09-04", "2020-12-31"), "latest": (None, None)}
LATEST_BARS = 300


def main() -> int:
    full = {
        sym: fetch.fetch_index(sym, use_cache=True, api_key="unused-cache-only").rows
        for sym in fetch.DEFAULT_SYMBOLS
    }
    out = {"note": "Real FMP EOD bars; generated by scripts/make_fixtures.py", "segments": {}}
    for name, (lo, hi) in SEGMENTS.items():
        seg = {}
        for sym, rows in full.items():
            if lo:
                seg[sym] = [r for r in rows if lo <= r["date"] <= hi]
            else:
                seg[sym] = rows[-LATEST_BARS:]
        out["segments"][name] = seg
    path = ROOT / "tests" / "fixtures" / "bars.json"
    path.write_text(json.dumps(out, separators=(",", ":")))
    print(f"wrote {path} ({path.stat().st_size} bytes) generated {date.today()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
